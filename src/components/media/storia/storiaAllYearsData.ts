function vaultPreviewVideo(idx: number, labelOffset: number): VideoSeed {
  const id = VAULT_PREVIEW_IDS[idx % VAULT_PREVIEW_IDS.length];
  return {
    src: `/movie/previews/${id}.mp4`,
    posterSrc: `/images/media/video-frames/${id}.jpg`,
    label: VAULT_VIDEO_LABELS[(idx + labelOffset) % VAULT_VIDEO_LABELS.length],
  };
}

function vaultFramePhoto(idx: number, labelOffset: number): { src: string; label: string } {
  const id = VAULT_PREVIEW_IDS[idx % VAULT_PREVIEW_IDS.length];
  return {
    src: `/images/media/video-frames/${id}.jpg`,
    label: VAULT_FRAME_LABELS[(idx + labelOffset) % VAULT_FRAME_LABELS.length],
  };
}

function buildYearMediaGallery(
  m: Omit<StoriaMilestone, "mediaGallery">,
  yearIdx: number
): readonly StoriaGalleryTile[] {
  const usedSrc = new Set<string>();

  const heroVideo: VideoSeed =
    YEAR_HERO_VIDEO_OVERRIDES[m.yearNum] ??
    (yearIdx % 2 === 0
      ? STAGE_FEATURE_VIDEOS[(yearIdx / 2) % STAGE_FEATURE_VIDEOS.length]
      : vaultPreviewVideo(yearIdx * 2, 0));
  usedSrc.add(heroVideo.src);

  let secondVideo = vaultPreviewVideo(yearIdx * 2 + 1, 1);
  if (usedSrc.has(secondVideo.src)) {
    secondVideo = vaultPreviewVideo(yearIdx * 2 + 15, 2);
  }
  usedSrc.add(secondVideo.src);
  usedSrc.add(secondVideo.posterSrc);

  let thirdVideo = vaultPreviewVideo((yearIdx * 2 + 42) % VAULT_PREVIEW_IDS.length, 3);
  if (usedSrc.has(thirdVideo.src)) {
    thirdVideo = STAGE_FEATURE_VIDEOS[(yearIdx + 3) % STAGE_FEATURE_VIDEOS.length];
  }
  usedSrc.add(thirdVideo.src);
  usedSrc.add(thirdVideo.posterSrc);

  const photoPool =
    m.yearNum >= 2016
      ? [...CRUISE_ERA_PHOTOS, ...STAGE_ARCHIVAL_PHOTOS]
      : STAGE_ARCHIVAL_PHOTOS;

  const pickUniquePhoto = (
    candidates: readonly { src: string; label: string }[],
    startIdx: number
  ): { src: string; label: string } => {
    for (let step = 0; step < candidates.length; step++) {
      const candidate = candidates[(startIdx + step) % candidates.length];
      if (!usedSrc.has(candidate.src)) {
        usedSrc.add(candidate.src);
        return candidate;
      }
    }
    const fallback = vaultFramePhoto(yearIdx * 3 + startIdx, 4);
    usedSrc.add(fallback.src);
    return fallback;
  };

  usedSrc.add(m.imageSrc);
  const primaryPhoto = { src: m.imageSrc, label: `${m.year} Milestone` };

  const secondaryPhoto = !usedSrc.has(m.secondaryImageSrc)
    ? (usedSrc.add(m.secondaryImageSrc),
      { src: m.secondaryImageSrc, label: m.themeLabel })
    : pickUniquePhoto(photoPool, yearIdx * 3 + 1);

  const panoramicPhoto = pickUniquePhoto(
    m.yearNum >= 2016 ? CRUISE_ERA_PHOTOS : STAGE_ARCHIVAL_PHOTOS,
    yearIdx * 2 + 3
  );

  const vaultStillA = pickUniquePhoto(
    [
      vaultFramePhoto((yearIdx * 2 + 19) % VAULT_PREVIEW_IDS.length, 0),
      vaultFramePhoto((yearIdx * 2 + 29) % VAULT_PREVIEW_IDS.length, 1),
      ...photoPool,
    ],
    0
  );

  const vaultStillB = pickUniquePhoto(
    [
      vaultFramePhoto((yearIdx * 2 + 57) % VAULT_PREVIEW_IDS.length, 2),
      vaultFramePhoto((yearIdx * 2 + 67) % VAULT_PREVIEW_IDS.length, 3),
      ...photoPool,
    ],
    0
  );

  // 8-tile mosaic layout order:
  // [0] Hero Video (6x2), [1] Stage Cam Video (3x1), [2] Primary Era Photo (3x1),
  // [3] Wide Panoramic Photo (6x1), [4] Companion Era Photo (3x1), [5] Vault Frame Photo A (3x1),
  // [6] Broadcast/Encore Video (3x1), [7] Vault Frame Photo B (3x1)
  return [
    {
      id: `${m.id}-tile-0`,
      kind: "video",
      src: heroVideo.src,
      posterSrc: heroVideo.posterSrc,
      alt: `${m.year} ${m.title} — ${heroVideo.label}`,
      label: heroVideo.label,
    },
    {
      id: `${m.id}-tile-1`,
      kind: "video",
      src: secondVideo.src,
      posterSrc: secondVideo.posterSrc,
      alt: `${m.year} ${m.venueMeta} — ${secondVideo.label}`,
      label: secondVideo.label,
    },
    {
      id: `${m.id}-tile-2`,
      kind: "photo",
      src: primaryPhoto.src,
      posterSrc: primaryPhoto.src,
      alt: m.imageAlt,
      label: primaryPhoto.label,
    },
    {
      id: `${m.id}-tile-3`,
      kind: "photo",
      src: panoramicPhoto.src,
      posterSrc: panoramicPhoto.src,
      alt: `${m.year} ${panoramicPhoto.label} — ${m.venueMeta}`,
      label: panoramicPhoto.label,
    },
    {
      id: `${m.id}-tile-4`,
      kind: "photo",
      src: secondaryPhoto.src,
      posterSrc: secondaryPhoto.src,
      alt: m.secondaryImageAlt || `${m.year} ${secondaryPhoto.label}`,
      label: secondaryPhoto.label,
    },
    {
      id: `${m.id}-tile-5`,
      kind: "photo",
      src: vaultStillA.src,
      posterSrc: vaultStillA.src,
      alt: `${m.year} ${vaultStillA.label}`,
      label: vaultStillA.label,
    },
    {
      id: `${m.id}-tile-6`,
      kind: "video",
      src: thirdVideo.src,
      posterSrc: thirdVideo.posterSrc,
      alt: `${m.year} ${thirdVideo.label}`,
      label: thirdVideo.label,
    },
    {
      id: `${m.id}-tile-7`,
      kind: "photo",
      src: vaultStillB.src,
      posterSrc: vaultStillB.src,
      alt: `${m.year} ${vaultStillB.label}`,
      label: vaultStillB.label,
    },
  ];
}

